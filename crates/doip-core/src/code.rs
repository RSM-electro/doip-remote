//! Portable, copy-pasteable session codes.
//!
//! A session code is a compact JSON document encoded with URL-safe Base64
//! (without padding) and prefixed with [`CODE_PREFIX`]. Short JSON keys keep
//! the resulting string as small as possible.

use std::{fmt, str::FromStr};

use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Prefix that identifies a `doip-remote` session code.
pub const CODE_PREFIX: &str = "DT1-";

/// Default DoIP port defined by ISO 13400.
pub const DEFAULT_DOIP_PORT: u16 = 13400;

/// The side of the tunnel a session belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// The agent running next to the vehicle.
    Car,
    /// The remote diagnostic client.
    Diag,
}

impl Role {
    /// Returns the wire representation of the role.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Car => "car",
            Self::Diag => "diag",
        }
    }
}

impl fmt::Display for Role {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

impl FromStr for Role {
    type Err = Error;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value.to_ascii_lowercase().as_str() {
            "car" => Ok(Self::Car),
            "diag" => Ok(Self::Diag),
            _ => Err(Error::InvalidRole(value.to_owned())),
        }
    }
}

/// Everything needed to join a remote diagnostic session.
///
/// Use [`SessionCode::new`] to create a fresh session with random identifiers,
/// then [`SessionCode::generate`] to produce a shareable `DT1-...` string.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionCode {
    /// Side of the tunnel that owns this code.
    pub role: Role,
    /// Relay server address, for example `diag.example.com:13500`.
    pub server: String,
    /// Unique session identifier.
    pub session_id: String,
    /// Session token used for authentication.
    pub token: String,
    /// Session key used for payload encryption.
    pub key: String,
    /// Whether the tunnel should run in bridge mode.
    pub bridge: bool,
    /// DoIP port on the vehicle side. Defaults to [`DEFAULT_DOIP_PORT`].
    pub doip_port: u16,
    /// Vehicle IP address, if known. `None` means auto-detection.
    pub vehicle_ip: Option<String>,
}

impl SessionCode {
    /// Creates a new session with freshly generated identifiers.
    ///
    /// The token and key are UUID v4 values, which is sufficient for the
    /// skeleton. Real key agreement will arrive with the network layer.
    #[must_use]
    pub fn new(role: Role, server: impl Into<String>, vehicle_ip: Option<String>) -> Self {
        Self {
            role,
            server: server.into(),
            session_id: Uuid::new_v4().to_string(),
            token: Uuid::new_v4().simple().to_string(),
            key: Uuid::new_v4().simple().to_string(),
            bridge: true,
            doip_port: DEFAULT_DOIP_PORT,
            vehicle_ip,
        }
    }

    /// Serializes the session into a shareable `DT1-...` code.
    ///
    /// The payload is compact JSON encoded as URL-safe Base64 without padding.
    #[must_use]
    pub fn generate(&self) -> String {
        let wire = Wire::from(self);
        let json = serde_json::to_vec(&wire).expect("SessionCode is always serializable");

        format!("{CODE_PREFIX}{}", URL_SAFE_NO_PAD.encode(json))
    }

    /// Parses a `DT1-...` code generated by [`SessionCode::generate`].
    ///
    /// Whitespace is ignored anywhere in the input, so codes copied from a
    /// wrapped terminal line (or with an accidental trailing newline) still
    /// parse correctly.
    pub fn parse(code: &str) -> Result<Self, Error> {
        let compact: String = code
            .chars()
            .filter(|character| !character.is_whitespace())
            .collect();
        let payload = compact
            .strip_prefix(CODE_PREFIX)
            .ok_or(Error::MissingPrefix)?;

        if payload.is_empty() {
            return Err(Error::EmptyPayload);
        }

        let bytes = URL_SAFE_NO_PAD.decode(payload)?;
        let wire: Wire = serde_json::from_slice(&bytes)?;

        Self::try_from(wire)
    }

    fn validate(&self) -> Result<(), Error> {
        let required_fields = [
            ("server", self.server.as_str()),
            ("session_id", self.session_id.as_str()),
            ("token", self.token.as_str()),
            ("key", self.key.as_str()),
        ];

        for (field, value) in required_fields {
            if value.trim().is_empty() {
                return Err(Error::EmptyField { field });
            }
        }

        if self.doip_port == 0 {
            return Err(Error::InvalidDoipPort);
        }

        Ok(())
    }
}

/// Compact on-the-wire representation of [`SessionCode`].
#[derive(Debug, Serialize, Deserialize)]
struct Wire {
    /// Role: `car` or `diag`.
    r: String,
    /// Relay server.
    s: String,
    /// Session identifier.
    n: String,
    /// Session token.
    t: String,
    /// Session key.
    k: String,
    /// Bridge mode.
    #[serde(default)]
    l: bool,
    /// DoIP port.
    #[serde(default = "default_doip_port")]
    p: u16,
    /// Vehicle IP address.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    v: Option<String>,
}

const fn default_doip_port() -> u16 {
    DEFAULT_DOIP_PORT
}

impl From<&SessionCode> for Wire {
    fn from(session: &SessionCode) -> Self {
        Self {
            r: session.role.as_str().to_owned(),
            s: session.server.clone(),
            n: session.session_id.clone(),
            t: session.token.clone(),
            k: session.key.clone(),
            l: session.bridge,
            p: session.doip_port,
            v: session.vehicle_ip.clone(),
        }
    }
}

impl TryFrom<Wire> for SessionCode {
    type Error = Error;

    fn try_from(wire: Wire) -> Result<Self, Self::Error> {
        let session = Self {
            role: wire.r.parse()?,
            server: wire.s.trim().to_owned(),
            session_id: wire.n,
            token: wire.t,
            key: wire.k,
            bridge: wire.l,
            doip_port: wire.p,
            vehicle_ip: wire.v.and_then(|ip| {
                let ip = ip.trim();
                (!ip.is_empty()).then(|| ip.to_owned())
            }),
        };

        session.validate()?;
        Ok(session)
    }
}

/// Errors produced while parsing or validating a session code.
#[derive(Debug, thiserror::Error)]
pub enum Error {
    /// The input does not start with [`CODE_PREFIX`].
    #[error("invalid session code: the `DT1-` prefix is missing")]
    MissingPrefix,

    /// The input consists only of the prefix.
    #[error("invalid session code: the payload after `DT1-` is empty")]
    EmptyPayload,

    /// The payload is not valid URL-safe Base64.
    #[error("invalid session code: Base64 decoding failed: {0}")]
    Base64(#[from] base64::DecodeError),

    /// The decoded payload is not valid JSON or is missing required fields.
    #[error("invalid session code: malformed JSON payload: {0}")]
    Json(#[from] serde_json::Error),

    /// The JSON payload contains an unknown role.
    #[error("invalid session code: unknown role `{0}` (expected `car` or `diag`)")]
    InvalidRole(String),

    /// A required field is empty.
    #[error("invalid session code: field `{field}` must not be empty")]
    EmptyField {
        /// Name of the offending field.
        field: &'static str,
    },

    /// The DoIP port is zero.
    #[error("invalid session code: DoIP port must be non-zero")]
    InvalidDoipPort,
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample(role: Role, vehicle_ip: Option<&str>) -> SessionCode {
        SessionCode {
            role,
            server: "diag.example.com:13500".to_owned(),
            session_id: "session-42".to_owned(),
            token: "token-value".to_owned(),
            key: "key-value".to_owned(),
            bridge: true,
            doip_port: DEFAULT_DOIP_PORT,
            vehicle_ip: vehicle_ip.map(ToOwned::to_owned),
        }
    }

    fn encode(json: &str) -> String {
        format!("{CODE_PREFIX}{}", URL_SAFE_NO_PAD.encode(json))
    }

    fn decode_json(code: &str) -> serde_json::Value {
        let payload = code.strip_prefix(CODE_PREFIX).expect("prefix");
        let bytes = URL_SAFE_NO_PAD.decode(payload).expect("valid base64");
        serde_json::from_slice(&bytes).expect("valid json")
    }

    #[test]
    fn generates_and_parses_a_car_session() {
        let session = sample(Role::Car, Some("192.168.1.10"));

        let code = session.generate();

        assert!(code.starts_with(CODE_PREFIX));
        assert_eq!(SessionCode::parse(&code).expect("parse"), session);
    }

    #[test]
    fn generates_and_parses_a_diag_session_without_vehicle_ip() {
        let session = sample(Role::Diag, None);

        let code = session.generate();
        let parsed = SessionCode::parse(&code).expect("parse");

        assert_eq!(parsed, session);
        assert_eq!(parsed.vehicle_ip, None);
    }

    #[test]
    fn generated_code_uses_unpadded_url_safe_base64() {
        let code = sample(Role::Car, None).generate();
        let payload = code.strip_prefix(CODE_PREFIX).expect("prefix");

        assert!(!payload.contains('='));
        assert!(!payload.contains('+'));
        assert!(!payload.contains('/'));
    }

    #[test]
    fn generated_json_uses_short_keys() {
        let code = sample(Role::Diag, Some("10.0.0.2")).generate();
        let json = decode_json(&code);
        let object = json.as_object().expect("object");

        let mut keys: Vec<&str> = object.keys().map(String::as_str).collect();
        keys.sort_unstable();

        assert_eq!(keys, ["k", "l", "n", "p", "r", "s", "t", "v"]);
        assert_eq!(json["r"], "diag");
        assert_eq!(json["s"], "diag.example.com:13500");
        assert_eq!(json["n"], "session-42");
        assert_eq!(json["t"], "token-value");
        assert_eq!(json["k"], "key-value");
        assert_eq!(json["l"], true);
        assert_eq!(json["p"], DEFAULT_DOIP_PORT);
        assert_eq!(json["v"], "10.0.0.2");
    }

    #[test]
    fn omits_vehicle_ip_when_absent() {
        let code = sample(Role::Car, None).generate();

        assert!(decode_json(&code).get("v").is_none());
    }

    #[test]
    fn parses_surrounding_whitespace() {
        let session = sample(Role::Car, Some("192.168.1.10"));
        let code = format!("  {}\n", session.generate());

        assert_eq!(SessionCode::parse(&code).expect("parse"), session);
    }

    #[test]
    fn ignores_whitespace_inside_the_payload() {
        let session = sample(Role::Car, Some("192.168.1.10"));
        let code = session.generate();
        let (prefix, payload) = code.split_at(CODE_PREFIX.len());
        let wrapped = format!("{prefix}{}\n\t  {}", &payload[..32], &payload[32..]);

        assert_eq!(SessionCode::parse(&wrapped).expect("parse"), session);
    }

    #[test]
    fn applies_defaults_for_missing_optional_fields() {
        let code = encode(r#"{"r":"diag","s":"relay:13500","n":"n","t":"t","k":"k"}"#);
        let session = SessionCode::parse(&code).expect("parse");

        assert_eq!(session.role, Role::Diag);
        assert!(!session.bridge);
        assert_eq!(session.doip_port, DEFAULT_DOIP_PORT);
        assert_eq!(session.vehicle_ip, None);
    }

    #[test]
    fn rejects_codes_without_the_prefix() {
        let error = SessionCode::parse("eyJyb2xlIjoiY2FyIn0").expect_err("must fail");

        assert!(matches!(error, Error::MissingPrefix));
    }

    #[test]
    fn rejects_an_empty_payload() {
        let error = SessionCode::parse("DT1-").expect_err("must fail");

        assert!(matches!(error, Error::EmptyPayload));
    }

    #[test]
    fn rejects_invalid_base64() {
        let error = SessionCode::parse("DT1-***").expect_err("must fail");

        assert!(matches!(error, Error::Base64(_)));
    }

    #[test]
    fn rejects_invalid_json() {
        let code = encode("this is not json");
        let error = SessionCode::parse(&code).expect_err("must fail");

        assert!(matches!(error, Error::Json(_)));
    }

    #[test]
    fn rejects_unknown_roles() {
        let code = encode(r#"{"r":"truck","s":"s","n":"n","t":"t","k":"k"}"#);
        let error = SessionCode::parse(&code).expect_err("must fail");

        assert!(matches!(error, Error::InvalidRole(role) if role == "truck"));
    }

    #[test]
    fn rejects_empty_required_fields() {
        let code = encode(r#"{"r":"car","s":"   ","n":"n","t":"t","k":"k"}"#);
        let error = SessionCode::parse(&code).expect_err("must fail");

        assert!(matches!(error, Error::EmptyField { field: "server" }));
    }

    #[test]
    fn rejects_zero_doip_port() {
        let code = encode(r#"{"r":"car","s":"s","n":"n","t":"t","k":"k","p":0}"#);
        let error = SessionCode::parse(&code).expect_err("must fail");

        assert!(matches!(error, Error::InvalidDoipPort));
    }

    #[test]
    fn new_creates_distinct_sessions_with_sane_defaults() {
        let first = SessionCode::new(Role::Car, "auto", Some("192.168.1.10".to_owned()));
        let second = SessionCode::new(Role::Car, "auto", None);

        assert_ne!(first.session_id, second.session_id);
        assert_ne!(first.token, second.token);
        assert_ne!(first.key, second.key);
        assert_eq!(first.doip_port, DEFAULT_DOIP_PORT);
        assert!(first.bridge);
        assert_eq!(first.token.len(), 32);
        assert_eq!(first.key.len(), 32);
        assert_eq!(first.vehicle_ip.as_deref(), Some("192.168.1.10"));
    }

    #[test]
    fn role_roundtrips_through_strings() {
        for role in [Role::Car, Role::Diag] {
            assert_eq!(role.as_str().parse::<Role>().expect("parse"), role);
            assert_eq!(role.to_string(), role.as_str());
        }
    }
}
